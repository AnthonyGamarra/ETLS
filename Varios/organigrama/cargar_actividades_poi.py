#!/usr/bin/env python3
"""
Carga las actividades operativas del POI en dwsge.actividades_poi.

Uso:
    pip install psycopg2-binary pandas openpyxl
    python cargar_actividades_poi.py                                   # Excel por defecto, año 2026
    python cargar_actividades_poi.py --excel ruta\\poi_2027.xlsx --anio 2027 --env ruta\\.env

Solo se cargan las actividades cuyo centro de costo (COD C.C.) existe en
dwsge.centro_de_costo_afessalud_homologado; las demás se listan y se omiten.
No se carga la columna "Detalle de la actividad".
La tabla acumula años: cada carga reemplaza solo las filas de su año, en una sola transacción.
COD A.O. no es único en el Excel, por eso la tabla usa un id propio.
"""
import argparse
import io
import sys
from pathlib import Path

try:
    import pandas as pd
    import psycopg2
except ImportError:
    sys.exit("Faltan librerías. Instala con:  pip install psycopg2-binary pandas openpyxl")

from cargar_organigrama import buscar_env, leer_env

EXCEL_DEFECTO = Path.home() / "Desktop" / "GGI" / "organigrama" / "actividades_poi.xlsx"

# columna del Excel -> columna de la tabla
COLUMNAS = {
    "Órgano Central": "organo_central",
    "COD O.E.": "cod_objetivo_estrategico",
    "COD A.E.": "cod_accion_estrategica",
    "COD C.G.": "cod_centro_gestor",
    "Centro gestor": "centro_gestor",
    "COD C.C.": "ce_coste",
    "Centro de costo": "centro_de_costo",
    "COD F.F.": "cod_fondo_financiero",
    "Fondo Financiero": "fondo_financiero",
    "COD A.O.": "cod_actividad_operativa",
    "Actividad operativa": "actividad_operativa",
    "Unidad de medida": "unidad_medida",
    "I": "meta_i",
    "II": "meta_ii",
    "III": "meta_iii",
    "IV": "meta_iv",
    "Remuneraciones": "remuneraciones",
    "Bienes": "bienes",
    "Servicios": "servicios",
}
NUMERICAS = ["meta_i", "meta_ii", "meta_iii", "meta_iv", "remuneraciones", "bienes", "servicios"]

DDL = """
CREATE TABLE IF NOT EXISTS dwsge.actividades_poi (
    id_actividad_poi          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio                      smallint     NOT NULL,
    organo_central           varchar(100) NOT NULL,
    cod_objetivo_estrategico  varchar(5)   NOT NULL,
    cod_accion_estrategica    varchar(10)  NOT NULL,
    cod_centro_gestor         varchar(15)  NOT NULL,
    centro_gestor             varchar(20)  NOT NULL,
    ce_coste                  varchar(20)  NOT NULL,
    centro_de_costo           varchar(120) NOT NULL,
    cod_fondo_financiero      varchar(10)  NOT NULL,
    fondo_financiero          varchar(80)  NOT NULL,
    cod_actividad_operativa   varchar(20)  NOT NULL,
    actividad_operativa       text         NOT NULL,
    unidad_medida             varchar(200) NOT NULL,
    meta_i                    numeric      NOT NULL,
    meta_ii                   numeric      NOT NULL,
    meta_iii                  numeric      NOT NULL,
    meta_iv                   numeric      NOT NULL,
    remuneraciones            numeric(18,2) NOT NULL,
    bienes                    numeric(18,2) NOT NULL,
    servicios                 numeric(18,2) NOT NULL,
    fuente                    varchar(100) NOT NULL,
    fecha_carga               timestamp    NOT NULL DEFAULT now()
);
COMMENT ON TABLE  dwsge.actividades_poi IS 'Actividades operativas del POI cuyo centro de costo está homologado al organigrama.';
COMMENT ON COLUMN dwsge.actividades_poi.ce_coste IS 'Centro de costo (COD C.C.); se cruza con dwsge.centro_de_costo_afessalud_homologado.ce_coste.';
COMMENT ON COLUMN dwsge.actividades_poi.cod_actividad_operativa IS 'COD A.O. del Excel; no es único.';
COMMENT ON COLUMN dwsge.actividades_poi.meta_i IS 'Meta del I trimestre, en la unidad de medida de la actividad (no sumar entre actividades).';
CREATE INDEX IF NOT EXISTS ix_actividades_poi_ce_coste ON dwsge.actividades_poi (ce_coste);
CREATE INDEX IF NOT EXISTS ix_actividades_poi_anio ON dwsge.actividades_poi (anio);
COMMENT ON COLUMN dwsge.actividades_poi.anio IS 'Año del POI.';
"""


def main():
    ap = argparse.ArgumentParser(description="Carga las actividades del POI en dwsge.actividades_poi")
    ap.add_argument("--excel", default=str(EXCEL_DEFECTO), help="ruta al Excel")
    ap.add_argument("--anio", type=int, default=2026, help="año del POI (por defecto 2026)")
    ap.add_argument("--env", help="ruta al archivo .env")
    args = ap.parse_args()
    if not 2000 <= args.anio <= 2100:
        sys.exit("Año inválido: %s" % args.anio)

    ruta = Path(args.excel)
    df = pd.read_excel(ruta, dtype=str)
    faltan = [c for c in COLUMNAS if c not in df.columns]
    if faltan:
        sys.exit("Al Excel le faltan columnas: " + ", ".join(faltan))
    df = df[list(COLUMNAS)].rename(columns=COLUMNAS).apply(lambda s: s.str.strip())
    vacias = df.isna() | df.eq("")
    if vacias.any().any():
        sys.exit("Hay celdas vacías en: " + ", ".join(df.columns[vacias.any()]))
    for c in NUMERICAS:
        df[c] = pd.to_numeric(df[c], errors="raise")
    for c in ("remuneraciones", "bienes", "servicios"):
        df[c] = df[c].round(2)
    df.insert(0, "anio", args.anio)
    df["fuente"] = ruta.name
    print("Excel: %s -> POI %d (%d actividades)" % (ruta.name, args.anio, len(df)))

    env = leer_env(buscar_env(args.env))
    conn = psycopg2.connect(host=env["PG_HOST"], port=env.get("PG_PORT", "5432"), dbname=env["PG_DB"],
                            user=env["PG_USER"], password=env["PG_PASS"], connect_timeout=10)
    with conn, conn.cursor() as cur:      # una sola transacción: si algo falla, la tabla queda como estaba
        cur.execute("SELECT ce_coste FROM dwsge.centro_de_costo_afessalud_homologado")
        homologados = {r[0] for r in cur.fetchall()}
        cruza = df["ce_coste"].isin(homologados)
        omitidas = df[~cruza]
        if len(omitidas):
            print("\nActividades omitidas por centro de costo no homologado: %d" % len(omitidas))
            for (cc, nombre), g in omitidas.groupby(["ce_coste", "centro_de_costo"]):
                print("  %s  %-40s %d" % (cc, nombre, len(g)))
        df = df[cruza]

        cur.execute(DDL)
        cur.execute("DELETE FROM dwsge.actividades_poi WHERE anio = %s", (args.anio,))
        if cur.rowcount:
            print("Reemplazando %d filas previas del POI %d" % (cur.rowcount, args.anio))
        buf = io.StringIO()
        df.to_csv(buf, index=False, header=False)
        buf.seek(0)
        cur.copy_expert("COPY dwsge.actividades_poi (%s) FROM STDIN WITH (FORMAT csv)" % ", ".join(df.columns), buf)

        print("\nValidaciones")
        cur.execute("""SELECT count(*), count(DISTINCT ce_coste), sum(remuneraciones + bienes + servicios)
                       FROM dwsge.actividades_poi WHERE anio = %s""", (args.anio,))
        total, cecos, monto = cur.fetchone()
        print("  actividades cargadas: %d (que cruzan en el Excel: %d)" % (total, len(df)))
        print("  centros de costo: %d" % cecos)
        print("  presupuesto total: %s" % format(monto, ",.2f"))
        if total != len(df):
            raise SystemExit("La cantidad cargada no coincide con el Excel; se revierte la carga.")
    conn.close()
    print("\nResultado: CARGA CORRECTA")


if __name__ == "__main__":
    main()
