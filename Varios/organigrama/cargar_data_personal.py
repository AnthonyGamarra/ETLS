#!/usr/bin/env python3
"""
Carga el maestro mensual de personal (Excel exportado de SAP) en dwsge.data_personal.

Uso:
    pip install psycopg2-binary pandas openpyxl
    python cargar_data_personal.py ruta\\AGOSTO2026.xlsx                 # periodo tomado del nombre: 202608
    python cargar_data_personal.py ruta\\archivo.xlsx --periodo 202609 --env ruta\\.env

La tabla acumula meses. Cada carga reemplaza solo las filas de su periodo, en una sola transacción.
Un mismo Nº pers. puede venir dos veces si la persona tiene DNI y carné de extranjería; se cargan ambas filas.
"""
import argparse
import io
import re
import sys
from pathlib import Path

try:
    import pandas as pd
    import psycopg2
except ImportError:
    sys.exit("Faltan librerías. Instala con:  pip install psycopg2-binary pandas openpyxl")

from cargar_organigrama import buscar_env, leer_env

MESES = {"ENERO": 1, "FEBRERO": 2, "MARZO": 3, "ABRIL": 4, "MAYO": 5, "JUNIO": 6, "JULIO": 7, "AGOSTO": 8,
         "SETIEMBRE": 9, "SEPTIEMBRE": 9, "OCTUBRE": 10, "NOVIEMBRE": 11, "DICIEMBRE": 12}

# columna del Excel -> columna de la tabla
COLUMNAS = {
    "Nº pers.": "nro_personal",
    "Número de personal": "nombre_personal",
    "Área de nómina": "area_nomina",
    "Soc.": "cod_sociedad",
    "Sociedad": "sociedad",
    "DivP": "cod_division_personal",
    "División de personal": "division_personal",
    "SDvPer.": "cod_subdivision_personal",
    "Subdivisión de personal": "subdivision_personal",
    "GrPer": "cod_grupo_personal",
    "Grupo de personal": "grupo_personal",
    "ÁPers": "cod_area_personal",
    "Área de personal": "area_personal",
    "ReLab": "cod_relacion_laboral",
    "Relación laboral": "relacion_laboral",
    "Ce.coste": "ce_coste",
    "Centro de coste": "centro_de_coste",
    "Un.org.": "un_org",
    "Unidad organizativa": "unidad_organizativa",
    "Posición": "cod_posicion",
    "Posición.1": "posicion",
    "Función": "cod_funcion",
    "Función.1": "funcion",
    "Clave de sexo": "sexo",
    "Fecha nac.": "fecha_nacimiento",
    "Nacionalidad": "nacionalidad",
    "Clave para el estado civil": "estado_civil",
    "Ps": "pais",
    "ID": "cod_tipo_documento",
    "Clase de identificación (clase": "tipo_documento",
    "Número ID": "nro_documento",
    "CC": "cod_clase_contrato",
    "Clase de contrato": "clase_contrato",
    "Fecha": "fecha",
    "Gr.prof.": "cod_grupo_profesional",
    "Sg": "cod_subgrupo_profesional",
}

DDL = """
CREATE TABLE IF NOT EXISTS dwsge.data_personal (
    id_data_personal          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    periodo                   char(6)      NOT NULL,
    nro_personal              varchar(10)  NOT NULL,
    nombre_personal           varchar(80),
    area_nomina               varchar(30),
    cod_sociedad              varchar(4),
    sociedad                  varchar(30),
    cod_division_personal     varchar(4),
    division_personal         varchar(60),
    cod_subdivision_personal  varchar(4),
    subdivision_personal      varchar(40),
    cod_grupo_personal        varchar(2),
    grupo_personal            varchar(40),
    cod_area_personal         varchar(2),
    area_personal             varchar(30),
    cod_relacion_laboral      varchar(2),
    relacion_laboral          varchar(30),
    ce_coste                  varchar(20),
    centro_de_coste           varchar(60),
    un_org                    integer,
    unidad_organizativa       varchar(80),
    cod_posicion              varchar(10),
    posicion                  varchar(80),
    cod_funcion               varchar(10),
    funcion                   varchar(80),
    sexo                      varchar(15),
    fecha_nacimiento          date,
    nacionalidad              varchar(30),
    estado_civil              varchar(15),
    pais                      varchar(3),
    cod_tipo_documento        varchar(2),
    tipo_documento            varchar(40),
    nro_documento             varchar(15),
    cod_clase_contrato        varchar(2),
    clase_contrato            varchar(40),
    fecha                     date,
    cod_grupo_profesional     varchar(10),
    cod_subgrupo_profesional  varchar(2),
    fuente                    varchar(100) NOT NULL,
    fecha_carga               timestamp    NOT NULL DEFAULT now(),
    CONSTRAINT uq_data_personal_periodo_persona_doc UNIQUE (periodo, nro_personal, cod_tipo_documento)
);
COMMENT ON TABLE  dwsge.data_personal IS 'Maestro mensual de personal (SAP). Una foto por periodo; datos personales sensibles.';
COMMENT ON COLUMN dwsge.data_personal.periodo IS 'AAAAMM del mes de la foto.';
COMMENT ON COLUMN dwsge.data_personal.nombre_personal IS 'Nombre completo (columna "Número de personal" del Excel).';
COMMENT ON COLUMN dwsge.data_personal.ce_coste IS 'Centro de costo; se cruza con dwsge.centro_de_costo_afessalud_homologado.ce_coste.';
COMMENT ON COLUMN dwsge.data_personal.fecha IS 'Columna "Fecha" del Excel tal como viene de SAP.';
CREATE INDEX IF NOT EXISTS ix_data_personal_periodo  ON dwsge.data_personal (periodo);
CREATE INDEX IF NOT EXISTS ix_data_personal_ce_coste ON dwsge.data_personal (ce_coste);
CREATE INDEX IF NOT EXISTS ix_data_personal_nro_doc  ON dwsge.data_personal (nro_documento);
"""


def periodo_de_nombre(ruta: Path):
    m = re.fullmatch(r"([A-Za-z]+)[ _-]?(\d{4})", ruta.stem.strip())
    if m and m.group(1).upper() in MESES:
        return "%s%02d" % (m.group(2), MESES[m.group(1).upper()])
    return None


def main():
    ap = argparse.ArgumentParser(description="Carga el maestro mensual de personal en dwsge.data_personal")
    ap.add_argument("excel", help="ruta al Excel (ej. AGOSTO2026.xlsx)")
    ap.add_argument("--periodo", help="AAAAMM; por defecto se toma del nombre del archivo")
    ap.add_argument("--env", help="ruta al archivo .env")
    args = ap.parse_args()

    ruta = Path(args.excel)
    periodo = args.periodo or periodo_de_nombre(ruta)
    if not periodo or not re.fullmatch(r"20\d{2}(0[1-9]|1[0-2])", periodo):
        sys.exit("No pude deducir el periodo del nombre del archivo; indícalo con --periodo AAAAMM")

    df = pd.read_excel(ruta, dtype=str)
    faltan = [c for c in COLUMNAS if c not in df.columns]
    if faltan:
        sys.exit("Al Excel le faltan columnas: " + ", ".join(faltan))
    df = df[list(COLUMNAS)].rename(columns=COLUMNAS)
    df = df.apply(lambda s: s.str.strip()).replace("", None)
    for c in ("fecha_nacimiento", "fecha"):
        df[c] = pd.to_datetime(df[c], errors="raise").dt.strftime("%Y-%m-%d")
    df.insert(0, "periodo", periodo)
    df["fuente"] = ruta.name
    print("Excel: %s -> periodo %s (%d filas)" % (ruta.name, periodo, len(df)))

    buf = io.StringIO()
    df.to_csv(buf, index=False, header=False)
    buf.seek(0)

    env = leer_env(buscar_env(args.env))
    conn = psycopg2.connect(host=env["PG_HOST"], port=env.get("PG_PORT", "5432"), dbname=env["PG_DB"],
                            user=env["PG_USER"], password=env["PG_PASS"], connect_timeout=10)
    with conn, conn.cursor() as cur:      # una sola transacción: si algo falla, el periodo queda como estaba
        cur.execute(DDL)
        cur.execute("DELETE FROM dwsge.data_personal WHERE periodo = %s", (periodo,))
        if cur.rowcount:
            print("Reemplazando %d filas previas del periodo %s" % (cur.rowcount, periodo))
        cur.copy_expert("COPY dwsge.data_personal (%s) FROM STDIN WITH (FORMAT csv)" % ", ".join(df.columns), buf)

        print("\nValidaciones")
        cur.execute("SELECT count(*), count(DISTINCT nro_personal) FROM dwsge.data_personal WHERE periodo = %s", (periodo,))
        total, personas = cur.fetchone()
        print("  filas cargadas: %d (Excel: %d)" % (total, len(df)))
        print("  personas distintas (Nº pers.): %d" % personas)
        cur.execute("""SELECT count(*) FILTER (WHERE c.ce_coste IS NOT NULL), count(*)
                       FROM dwsge.data_personal p
                       LEFT JOIN (SELECT DISTINCT ce_coste FROM dwsge.centro_de_costo_afessalud_homologado) c USING (ce_coste)
                       WHERE p.periodo = %s""", (periodo,))
        con_cc, n = cur.fetchone()
        print("  filas cuyo centro de costo está en centro_de_costo_afessalud_homologado: %d de %d" % (con_cc, n))
        cur.execute("SELECT periodo, count(*) FROM dwsge.data_personal GROUP BY periodo ORDER BY periodo")
        print("  periodos en la tabla: " + ", ".join("%s (%d)" % r for r in cur.fetchall()))
        if total != len(df):
            raise SystemExit("La cantidad cargada no coincide con el Excel; se revierte la carga.")

        # la vista materializada del organigrama solo muestra el último periodo; se refresca para que tome esta carga
        cur.execute("SELECT 1 FROM pg_matviews WHERE schemaname = 'dwsge' AND matviewname = 'vw_organigrama_jerarquia_personal'")
        if cur.fetchone():
            cur.execute("REFRESH MATERIALIZED VIEW dwsge.vw_organigrama_jerarquia_personal")
            cur.execute("SELECT periodo, count(*) FROM dwsge.vw_organigrama_jerarquia_personal GROUP BY periodo")
            print("  vw_organigrama_jerarquia_personal refrescada: " + ", ".join("%s (%d personas)" % r for r in cur.fetchall()))
    conn.close()
    print("\nResultado: CARGA CORRECTA")


if __name__ == "__main__":
    main()
