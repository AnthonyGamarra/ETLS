#!/usr/bin/env python3
"""
Carga la homologación de centros de costo AFESSALUD -> organigrama en dwsge.centro_de_costo_afessalud_homologado.

Uso:
    pip install psycopg2-binary openpyxl
    python cargar_centro_costo.py                                  # Excel por defecto (ver EXCEL_DEFECTO)
    python cargar_centro_costo.py --excel ruta\\archivo.xlsx --env ruta\\.env

Cada fila del Excel enlaza un centro de costo (Ce.coste) con una unidad de dwsge.organigrama_unidad
por CODIGO_UNIDAD. Ce.coste es la llave: no puede repetirse (la carga se detiene si se repite).

El Excel es la fuente completa: cada carga reemplaza todo el contenido de la tabla en una sola transacción.
"""
import argparse
import sys
from pathlib import Path

try:
    import psycopg2
    from psycopg2.extras import execute_values
except ImportError:
    sys.exit("Falta psycopg2. Instala con:  pip install psycopg2-binary")
try:
    from openpyxl import load_workbook
except ImportError:
    sys.exit("Falta openpyxl. Instala con:  pip install openpyxl")

from cargar_organigrama import buscar_env, leer_env

EXCEL_DEFECTO = Path.home() / "Desktop" / "GGI" / "data_personal" / "centro_de_costo_afessalud_homologado_completo.xlsx"
COLUMNAS = ["Ce.coste", "Centro de coste", "Un.org.", "Unidad organizativa", "HOMOLOGADO", "CODIGO_UNIDAD"]

DDL = """
CREATE TABLE IF NOT EXISTS dwsge.centro_de_costo_afessalud_homologado (
    id_centro_costo      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ce_coste             varchar(20)  NOT NULL,
    centro_de_coste      varchar(100) NOT NULL,
    un_org               integer      NOT NULL,
    unidad_organizativa  varchar(150) NOT NULL,
    homologado           varchar(250) NOT NULL,
    codigo_unidad        varchar(60)  NOT NULL REFERENCES dwsge.organigrama_unidad (codigo),
    id_unidad            integer      NOT NULL REFERENCES dwsge.organigrama_unidad (id_unidad),
    fuente               varchar(100) NOT NULL DEFAULT 'centro_de_costo_afessalud_homologado.xlsx',
    fecha_carga          timestamp    NOT NULL DEFAULT now(),
    CONSTRAINT uq_cc_afessalud_ceco_unidad_org UNIQUE (ce_coste, unidad_organizativa)
);
COMMENT ON TABLE  dwsge.centro_de_costo_afessalud_homologado IS 'Centros de costo AFESSALUD homologados a las unidades del organigrama institucional.';
COMMENT ON COLUMN dwsge.centro_de_costo_afessalud_homologado.ce_coste IS 'Código del centro de costo (Ce.coste). Puede repetirse con distinta unidad_organizativa.';
COMMENT ON COLUMN dwsge.centro_de_costo_afessalud_homologado.un_org IS 'Código de la unidad organizativa en AFESSALUD (Un.org.).';
COMMENT ON COLUMN dwsge.centro_de_costo_afessalud_homologado.homologado IS 'Nombre de la unidad del organigrama con la que se homologó.';
COMMENT ON COLUMN dwsge.centro_de_costo_afessalud_homologado.codigo_unidad IS 'Código jerárquico en dwsge.organigrama_unidad.';
CREATE INDEX IF NOT EXISTS ix_cc_afessalud_id_unidad ON dwsge.centro_de_costo_afessalud_homologado (id_unidad);
CREATE INDEX IF NOT EXISTS ix_cc_afessalud_ce_coste  ON dwsge.centro_de_costo_afessalud_homologado (ce_coste);
"""

INSERT = """
INSERT INTO dwsge.centro_de_costo_afessalud_homologado
    (ce_coste, centro_de_coste, un_org, unidad_organizativa, homologado, codigo_unidad, id_unidad, fuente)
SELECT v.ce_coste, v.centro_de_coste, v.un_org, v.unidad_organizativa, v.homologado, v.codigo_unidad, u.id_unidad, %s
FROM (VALUES %%s) AS v (ce_coste, centro_de_coste, un_org, unidad_organizativa, homologado, codigo_unidad)
JOIN dwsge.organigrama_unidad u ON u.codigo = v.codigo_unidad
"""


def leer_excel(ruta: Path) -> list:
    hoja = load_workbook(ruta, read_only=True, data_only=True).worksheets[0]
    filas = hoja.iter_rows(values_only=True)
    cabecera = [str(c).strip() if c is not None else "" for c in next(filas)]
    faltan = [c for c in COLUMNAS if c not in cabecera]
    if faltan:
        sys.exit("Al Excel le faltan columnas: " + ", ".join(faltan))
    idx = [cabecera.index(c) for c in COLUMNAS]
    datos = []
    for n, fila in enumerate(filas, start=2):
        if all(v is None or str(v).strip() == "" for v in fila):
            continue
        v = [None if fila[i] is None else str(fila[i]).strip() for i in idx]
        if any(x in (None, "") for x in v):
            sys.exit("Fila %d del Excel tiene celdas vacías: %s" % (n, v))
        v[2] = int(float(v[2]))
        datos.append(tuple(v))
    return datos


def main():
    ap = argparse.ArgumentParser(description="Carga centros de costo AFESSALUD homologados en dwsge")
    ap.add_argument("--excel", default=str(EXCEL_DEFECTO), help="ruta al Excel")
    ap.add_argument("--env", help="ruta al archivo .env")
    args = ap.parse_args()

    fuente = Path(args.excel).name
    filas = leer_excel(Path(args.excel))
    print("Excel: %s (%d filas)" % (args.excel, len(filas)))
    vistos, repetidos = set(), set()
    for f in filas:
        (repetidos if f[0] in vistos else vistos).add(f[0])
    if repetidos:
        sys.exit("El Excel tiene Ce.coste repetidos: " + ", ".join(sorted(repetidos)))

    env = leer_env(buscar_env(args.env))
    conn = psycopg2.connect(host=env["PG_HOST"], port=env.get("PG_PORT", "5432"), dbname=env["PG_DB"],
                            user=env["PG_USER"], password=env["PG_PASS"], connect_timeout=10)
    with conn, conn.cursor() as cur:      # una sola transacción: si algo falla, no queda nada a medias
        cur.execute(DDL)
        codigos = sorted({f[5] for f in filas})
        cur.execute("SELECT codigo FROM dwsge.organigrama_unidad WHERE codigo = ANY(%s)", (codigos,))
        sin_unidad = set(codigos) - {r[0] for r in cur.fetchall()}
        if sin_unidad:
            raise SystemExit("CODIGO_UNIDAD que no existen en dwsge.organigrama_unidad: " + ", ".join(sorted(sin_unidad)))
        cur.execute("DELETE FROM dwsge.centro_de_costo_afessalud_homologado")
        if cur.rowcount:
            print("Reemplazando %d filas previas" % cur.rowcount)
        execute_values(cur, cur.mogrify(INSERT, (fuente,)).decode(), filas)
        cur.execute("CREATE UNIQUE INDEX IF NOT EXISTS ux_cc_afessalud_ce_coste "
                    "ON dwsge.centro_de_costo_afessalud_homologado (ce_coste)")

        print("\nValidaciones")
        cur.execute("SELECT count(*), count(DISTINCT ce_coste), count(DISTINCT id_unidad) "
                    "FROM dwsge.centro_de_costo_afessalud_homologado")
        total, cecos, unidades = cur.fetchone()
        print("  filas cargadas: %d (Excel: %d)" % (total, len(filas)))
        print("  centros de costo distintos: %d" % cecos)
        print("  unidades del organigrama con centro de costo: %d" % unidades)
        cur.execute("""SELECT count(*) FROM dwsge.centro_de_costo_afessalud_homologado c
                       JOIN dwsge.organigrama_unidad u ON u.id_unidad = c.id_unidad
                       WHERE u.codigo <> c.codigo_unidad OR u.nombre <> c.homologado""")
        print("  filas con código o nombre distinto al organigrama: %d" % cur.fetchone()[0])
        cur.execute("""SELECT count(*) FROM dwsge.organigrama_unidad u WHERE NOT EXISTS
                       (SELECT 1 FROM dwsge.centro_de_costo_afessalud_homologado c WHERE c.id_unidad = u.id_unidad)""")
        print("  unidades del organigrama sin centro de costo: %d" % cur.fetchone()[0])
        if total != len(filas):
            raise SystemExit("La cantidad cargada no coincide con el Excel; se revierte la carga.")
    conn.close()
    print("\nResultado: CARGA CORRECTA")


if __name__ == "__main__":
    main()
